"""Renders project_verification_certificate.pdf from the same JSON source of truth, via a
styled HTML intermediate (xhtml2pdf) -- a polished, presentation-ready layout distinct from
the plain Markdown, but reporting identical facts."""
from __future__ import annotations

import json
from pathlib import Path

from xhtml2pdf import pisa

PROJECT_ROOT = Path(__file__).resolve().parents[1]

with open(PROJECT_ROOT / "project_verification_certificate.json") as f:
    c = json.load(f)


def esc(s) -> str:
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def status_badge(ok: bool) -> str:
    color = "#1a7f37" if ok else "#c0392b"
    text = "PASS" if ok else "FAIL"
    return f'<span style="color:{color};font-weight:bold;">{text}</span>'


