def short_path(p: str, max_len: int = 34) -> str:
    """xhtml2pdf's table engine does not reliably support table-layout:fixed / colgroup
    widths, nor does it widen a column for nowrap content -- long text in one cell can
    visually overlap the next column regardless (a confirmed renderer limitation, not a
    config error; tested table-layout:fixed, colgroup widths, and white-space:nowrap, all
    ineffective). The reliable fix combines HTML4-attribute column widths (which this
    ReportLab-based engine DOES respect) with truncating cell content to fit inside them."""
    return p if len(p) <= max_len else "..." + p[-(max_len - 3):]

# Artifact inventory (compact) -- HTML4 width= attributes, not CSS, are what xhtml2pdf's
# table engine actually honors reliably.
html_parts.append("""<h2>6. Artifact Inventory</h2>
<table>
<tr><th width="33%">Filename</th><th width="30%">Purpose</th><th width="12%">Size</th><th width="25%">SHA-256 (prefix)</th></tr>""")
for a in c["artifact_inventory"]:
    size = f"{a['size_bytes']:,} B" if a["size_bytes"] else "MISSING"
    html_parts.append(f"<tr><td class='mono'>{esc(short_path(a['filename']))}</td><td>{esc(a['purpose'])}</td><td>{size}</td><td class='mono'>{esc(a['sha256'][:16])}...</td></tr>")
html_parts.append("</table>")

# Submission verification
html_parts.append("<h2>7. Submission Verification</h2><table><tr><th>Check</th><th>Status</th><th>Note</th></tr>")
for key, val in c["submission_verification"].items():
    if key == "final_submission_sha256":
        continue
    html_parts.append(f"<tr><td>{esc(key.replace('_',' ').capitalize())}</td><td>{status_badge(val['status'])}</td><td>{esc(val['note'])}</td></tr>")
html_parts.append(f"</table><p><b>Final submission SHA-256:</b> <span class='mono'>{esc(c['submission_verification']['final_submission_sha256'])}</span></p>")

# Validation checklist
html_parts.append("<h2>8. Validation Checklist</h2><table><tr><th>Item</th><th>Status</th></tr>")
for item in c["validation_checklist"]:
    html_parts.append(f"<tr><td>{esc(item['item'])}</td><td>{status_badge(item['status'])}</td></tr>")
html_parts.append("</table>")

# Known limitations
html_parts.append("<h2>9. Known Limitations</h2>")
for i, lim in enumerate(c["known_limitations"], 1):
    html_parts.append(f"<h3>{i}. {esc(lim['description'])}</h3>")
    html_parts.append(f"<p><i>Evidence:</i> {esc(lim['evidence'])}<br/>"
                       f"<i>Expected impact:</i> {esc(lim['expected_impact'])}<br/>"
                       f"<i>Mitigation:</i> {esc(lim['mitigation'])}</p>")

# Risk register
html_parts.append("<h2>10. Risk Register</h2><table><tr><th>Risk</th><th>Likelihood</th><th>Impact</th><th>Residual Risk</th></tr>")
for row in c["risk_register"]:
    html_parts.append(f"<tr><td>{esc(row['risk'])}</td><td>{esc(row['likelihood'])}</td><td>{esc(row['impact'])}</td><td>{esc(row['residual_risk'])}</td></tr>")
html_parts.append("</table>")

# Certification statement
html_parts.append(f"""
<h2>11. Certification Statement</h2>
<div class="cert-quote">{esc(c['certification_statement'])}</div>

<h2>12. Final Recommendation</h2>
<div class="badge-box">
  <div class="badge-title">{esc(c['final_recommendation']['recommendation'])}</div>
</div>
""")

if c["final_recommendation"]["required_actions"]:
    html_parts.append("<p><b>Required administrative action(s):</b></p><ol>")
    for action in c["final_recommendation"]["required_actions"]:
        html_parts.append(f"<li>{esc(action)}</li>")
    html_parts.append("</ol>")

html_parts.append(f"""
<div class="footer-note">
Rendered from project_verification_certificate.json (single source of truth for all 3
certificate formats). Repository: {esc(r['repository_name'])} | Commit: {esc(r['final_commit_hash'][:12])} |
Tag: {esc(r['release_tag'])}
</div>
</body>
</html>
""")

html = "".join(html_parts)
html_path = PROJECT_ROOT / "project_verification_certificate_render.html"
with open(html_path, "w", encoding="utf-8") as f:
    f.write(html)

pdf_path = PROJECT_ROOT / "project_verification_certificate.pdf"
with open(pdf_path, "wb") as f:
    result = pisa.CreatePDF(html, dest=f)

if result.err:
    print(f"PDF generation reported {result.err} error(s)")
else:
    print(f"Wrote {pdf_path}")
